const textState=new WeakMap();
const attrState=new WeakMap();
let applying=false;
function lang(){return String(localStorage.getItem('ait_lang')||document.documentElement.lang||'en').toLowerCase().startsWith('ar')?'ar':'en'}
const pairs=Object.keys(AR_EN).sort((a,b)=>b.length-a.length);
function translate(value){
  let out=String(value==null?'':value);
  if(!out.trim())return out;
  if(AR_EN[out.trim()]){
    const lead=(out.match(/^\s*/)||[''])[0],tail=(out.match(/\s*$/)||[''])[0];
    return lead+AR_EN[out.trim()]+tail;
  }
  for(const ar of pairs){if(out.includes(ar))out=out.split(ar).join(AR_EN[ar])}
  return out;
}
function processText(node){
  if(!node||node.nodeType!==3)return;
  const current=node.nodeValue;
  let state=textState.get(node);
  if(!state){state={source:current,last:null};textState.set(node,state)}
  else if(state.last!==null&&current!==state.last){state.source=current}
  const next=lang()==='ar'?state.source:translate(state.source);
  if(current!==next)node.nodeValue=next;
  state.last=next;
}
function processAttribute(el,name){
  if(!el.hasAttribute(name))return;
  let map=attrState.get(el);
  if(!map){map={};attrState.set(el,map)}
  const current=el.getAttribute(name);
  let state=map[name];
  if(!state){state={source:current,last:null};map[name]=state}
  else if(state.last!==null&&current!==state.last){state.source=current}
  const next=lang()==='ar'?state.source:translate(state.source);
  if(current!==next)el.setAttribute(name,next);
  state.last=next;
}
function processElement(el){
  if(!el||el.nodeType!==1)return;
  ['placeholder','title','aria-label'].forEach(name=>processAttribute(el,name));
  for(const node of el.childNodes){
    if(node.nodeType===3)processText(node);
    else if(node.nodeType===1)processElement(node);
  }
}
